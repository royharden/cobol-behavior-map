"""Inert descriptive summaries of supplied observations; no evidence is created here.

An ``actual`` label is a caller declaration, not authenticated custody or admission.
The expected frame must come from the independently frozen schedule, never the rows.
No function in this module dispatches, executes candidates, or reads artifacts.
"""
from __future__ import annotations

from dataclasses import dataclass
from fractions import Fraction
import random
import re
from typing import TYPE_CHECKING, Iterable

if TYPE_CHECKING:
    from cobolmap.contracts import TaskBinding

ARMS = ("A", "B", "C", "D", "R")
CONTRASTS = (("D", "C"), ("D", "R"), ("C", "B"), ("D", "B"), ("D", "A"))
FAILURES = frozenset({"fail", "refused", "invalid", "malformed", "crash", "fault",
                      "timeout", "forbidden", "import_violation", "output_cap", "resource_cap"})
UNMEASURED = frozenset({"unavailable", "not_run", "infra_invalid", "missing", "unknown"})


@dataclass(frozen=True)
class TaskSlot:
    task_id: str
    program_id: str
    family_id: str
    split: str
    panel: str
    model_slot: str


@dataclass(frozen=True)
class OutcomeRow(TaskSlot):
    arm: str
    outcome: str
    evidence_mode: str
    verification_cases: int | None = None
    passed_cases: int | None = None


def expected_slots(tasks: tuple[TaskBinding, ...]) -> tuple[TaskSlot, ...]:
    """Adapt the caller's frozen full native frame for both model slots.

    Structural validation does not authenticate schedule provenance or custody.
    No task, hidden data, approval, or observation is generated by this adapter.
    """
    from cobolmap.contracts import TaskBinding
    from .schedule import validate_tasks

    if not isinstance(tasks, tuple) or not all(isinstance(task, TaskBinding) for task in tasks):
        raise ValueError("tuple of native TaskBinding required")
    validate_tasks(tasks)
    return tuple(TaskSlot(task.task_id, task.program_id, task.family_id,
                          task.split, task.panel, model_slot)
                 for task in tasks for model_slot in ("primary", "replication"))


@dataclass(frozen=True)
class ArmSummary:
    arm: str
    scheduled: int
    measured: int
    passed: int
    failed: int
    refused: int
    unresolved: int
    pass_share: Fraction | None
    outcomes: tuple[tuple[str, int], ...]


@dataclass(frozen=True)
class PairedSummary:
    contrast: str
    family_values: tuple[tuple[str, Fraction | None], ...]
    mean_difference: Fraction | None
    interval_95: tuple[Fraction, Fraction] | None
    left_only_pass: int
    right_only_pass: int
    measured_pairs: int
    scheduled_pairs: int


@dataclass(frozen=True)
class StudySummary:
    split: str
    panel: str
    model_slot: str
    status: str
    issues: tuple[str, ...]
    arms: tuple[ArmSummary, ...]
    contrasts: tuple[PairedSummary, ...]
    bootstrap_draws: int = 10000
    bootstrap_seed: int = 20261027
    interpretation: str = "descriptive; effective n=6; sampling variability unmeasured"


def _identity(slot: TaskSlot) -> tuple[str, str, str, str, str, str]:
    return (slot.task_id, slot.program_id, slot.family_id, slot.split, slot.panel, slot.model_slot)


def _binary(row: OutcomeRow) -> int | None:
    if row.evidence_mode not in {"actual", "fixture", "static", "not_run"}:
        raise ValueError("unknown evidence_mode")
    if row.outcome not in FAILURES | UNMEASURED | {"pass"}:
        raise ValueError("unknown outcome")
    for count in (row.verification_cases, row.passed_cases):
        if count is not None and (type(count) is not int or not 0 <= count <= 128):
            raise ValueError("case counts must be integers in 0..128 or absent")
    if row.passed_cases is not None and (row.verification_cases is None or
                                        row.passed_cases > row.verification_cases):
        raise ValueError("passed cases require a consistent verification count")
    if row.outcome == "pass" and (row.verification_cases != 128 or row.passed_cases != 128):
        raise ValueError("pass requires all 128 verification cases passed")
    if row.outcome in FAILURES and row.passed_cases == 128:
        raise ValueError("failure contradicts 128 passed cases")
    if row.evidence_mode != "actual" or row.outcome in UNMEASURED:
        return None
    return int(row.outcome == "pass")


def _percentile(values: list[Fraction], quantile: Fraction) -> Fraction:
    """Linear interpolation at (n-1)*q, with exact rational arithmetic."""
    position = (len(values) - 1) * quantile
    lower = position.numerator // position.denominator
    upper = min(lower + 1, len(values) - 1)
    return values[lower] + (values[upper] - values[lower]) * (position - lower)


def summarize(rows: Iterable[OutcomeRow], expected: Iterable[TaskSlot], *,
              split: str, panel: str, model_slot: str) -> StudySummary:
    """Keep every arm/task in a separately supplied, complete six-family frame.

    Malformed or contradictory inputs raise; missing/unmeasured observations remain
    unresolved and suppress the affected complete rates, differences and intervals.
    Other panels/models/splits may be supplied but are never pooled.
    """
    if split not in {"dev", "heldout"} or panel not in {"unchanged", "change"} or not model_slot:
        raise ValueError("explicit split, panel and model_slot required")
    frame: dict[tuple[str, str, str, str], TaskSlot] = {}
    program_families: dict[str, str] = {}
    for slot in expected:
        if not isinstance(slot, TaskSlot) or not all(isinstance(x, str) and x for x in _identity(slot)):
            raise ValueError("expected frame requires nonempty TaskSlot metadata")
        if slot.split not in {"dev", "heldout"} or slot.panel not in {"unchanged", "change"}:
            raise ValueError("invalid expected split/panel")
        key = (slot.task_id, slot.split, slot.panel, slot.model_slot)
        if key in frame:
            raise ValueError("duplicate expected task slot")
        previous = program_families.setdefault(slot.program_id, slot.family_id)
        if previous != slot.family_id:
            raise ValueError("program family drift")
        frame[key] = slot
    selected = tuple(s for s in frame.values()
                     if (s.split, s.panel, s.model_slot) == (split, panel, model_slot))
    families = sorted({s.family_id for s in selected})
    per_family = 3 if split == "heldout" else 4
    if len(families) != 6 or any(
        len([s for s in selected if s.family_id == f]) != per_family or
        len({s.program_id for s in selected if s.family_id == f}) != per_family for f in families
    ):
        raise ValueError("expected frame must contain six families with exactly 3 heldout/4 dev programs each")
    observed: dict[tuple[str, str], tuple[OutcomeRow, int | None]] = {}
    all_keys: set[tuple[str, str, str, str, str]] = set()
    for row in rows:
        if not isinstance(row, OutcomeRow) or row.arm not in ARMS:
            raise ValueError("OutcomeRow with scheduled arm required")
        slot_key = (row.task_id, row.split, row.panel, row.model_slot)
        slot = frame.get(slot_key)
        if slot is None or _identity(slot) != _identity(row):
            raise ValueError("row outside independently supplied expected frame")
        key = (*slot_key, row.arm)
        if key in all_keys:
            raise ValueError("duplicate task/arm observation; resolve reexecution upstream")
        all_keys.add(key)
        value = _binary(row)
        if (row.split, row.panel, row.model_slot) == (split, panel, model_slot):
            observed[(row.task_id, row.arm)] = (row, value)
    issues: list[str] = []
    arms: list[ArmSummary] = []
    for arm in ARMS:
        values: list[int] = []
        counts: dict[str, int] = {}
        for slot in selected:
            item = observed.get((slot.task_id, arm))
            outcome = item[0].outcome if item else "missing"
            counts[outcome] = counts.get(outcome, 0) + 1
            value = item[1] if item else None
            if value is None:
                issues.append(f"{slot.task_id}/{arm}:unresolved")
            else:
                values.append(value)
        unresolved = len(selected) - len(values)
        arms.append(ArmSummary(arm, len(selected), len(values), sum(values),
                               len(values) - sum(values), counts.get("refused", 0), unresolved,
                               None if unresolved else Fraction(sum(values), len(selected)),
                               tuple(sorted(counts.items()))))
    contrasts: list[PairedSummary] = []
    for left, right in CONTRASTS:
        family_values: list[tuple[str, Fraction | None]] = []
        left_only = right_only = measured = 0
        for family in families:
            differences: list[int] = []
            for slot in selected:
                if slot.family_id != family:
                    continue
                a = observed.get((slot.task_id, left))
                b = observed.get((slot.task_id, right))
                if a is None or b is None or a[1] is None or b[1] is None:
                    continue
                measured += 1
                differences.append(a[1] - b[1])
                left_only += int(a[1] == 1 and b[1] == 0)
                right_only += int(a[1] == 0 and b[1] == 1)
            family_values.append((family, Fraction(sum(differences), per_family)
                                  if len(differences) == per_family else None))
        complete = all(value is not None for _, value in family_values)
        mean = interval = None
        if complete:
            six = [value for _, value in family_values if value is not None]
            mean = sum(six, Fraction()) / 6
            rng = random.Random(20261027)
            draws = sorted(sum((six[rng.randrange(6)] for _ in range(6)), Fraction()) / 6
                           for _ in range(10000))
            interval = (_percentile(draws, Fraction(1, 40)), _percentile(draws, Fraction(39, 40)))
        contrasts.append(PairedSummary(f"{left}-{right}", tuple(family_values), mean, interval,
                                       left_only, right_only, measured, len(selected)))
    return StudySummary(split, panel, model_slot, "incomplete" if issues else "complete",
                        tuple(issues), tuple(arms), tuple(contrasts))


@dataclass(frozen=True)
class AttemptCost:
    """Every attempt, selected or not; shared C is linked, never charged twice.

    cost_usd is exact nonnegative plain decimal text. 'known' must describe an
    actual resolved charge, including an explicitly evidenced zero; never infer it.
    This projection cannot authenticate billing or certify a complete app ledger.
    """
    call_id: str
    request_sha256: str
    arm: str
    task_id: str
    model_slot: str
    cost_usd: str | None = None
    liability_status: str = "unknown"
    shared_c_call_id: str | None = None
    raw_response_sha256: str | None = None


@dataclass(frozen=True)
class CostSummary:
    unique_calls: int
    known_usd: Fraction
    total_usd: Fraction | None
    unresolved_call_ids: tuple[str, ...]
    inclusive_arm_usd: tuple[tuple[str, Fraction | None], ...]
    coverage: str
    status: str
    issues: tuple[str, ...]


def summarize_costs(attempts: Iterable[AttemptCost], *,
                    expected_call_ids: tuple[str, ...] | None = None) -> CostSummary:
    """Project all supplied attempts; no retries, ledger storage, rate inference or I/O.

    D/R include their C charge even when no repair call was needed: supply the
    original C record and use its task/model identity. App total counts it once.
    Other app expenses must be included by the authoritative app ledger; this
    function's total is explicitly the supplied attempt set only.

    expected_call_ids must be the authoritative all-attempt ledger inventory,
    not unused maximum schedule slots. None leaves coverage unknown, even for an
    empty input. An explicit empty tuple declares no attempts only if separately
    authenticated by the caller; this module cannot authenticate that authority.
    """
    if expected_call_ids is not None and (
        not isinstance(expected_call_ids, tuple) or
        any(not isinstance(i, str) or not i for i in expected_call_ids) or
        len(set(expected_call_ids)) != len(expected_call_ids)
    ):
        raise ValueError("expected_call_ids must be an exact unique tuple of nonempty IDs")
    calls: dict[str, AttemptCost] = {}
    amounts: dict[str, Fraction | None] = {}
    for attempt in attempts:
        if not isinstance(attempt, AttemptCost):
            raise ValueError("AttemptCost required")
        if not all(isinstance(x, str) and x for x in
                   (attempt.call_id, attempt.task_id, attempt.model_slot)) or attempt.arm not in ARMS:
            raise ValueError("attempt identity/arm missing")
        if attempt.arm == "A":
            raise ValueError("A has no provider attempt or charge")
        if not re.fullmatch(r"[0-9a-f]{64}", attempt.request_sha256):
            raise ValueError("request hash required")
        if attempt.raw_response_sha256 is not None and not re.fullmatch(r"[0-9a-f]{64}", attempt.raw_response_sha256):
            raise ValueError("invalid response hash")
        if attempt.liability_status not in {"known", "unknown", "unavailable", "reserved"}:
            raise ValueError("unknown liability status")
        if attempt.shared_c_call_id is not None and attempt.arm not in {"D", "R"}:
            raise ValueError("only D/R may link shared C")
        amount = None
        if attempt.cost_usd is not None:
            if not isinstance(attempt.cost_usd, str) or not re.fullmatch(r"(?:0|[1-9][0-9]*)(?:\.[0-9]+)?", attempt.cost_usd):
                raise ValueError("cost requires exact nonnegative plain decimal text")
            amount = Fraction(attempt.cost_usd)
        if attempt.liability_status == "known" and amount is None:
            raise ValueError("known charge requires actual amount")
        if attempt.call_id in calls and calls[attempt.call_id] != attempt:
            raise ValueError("contradictory duplicate call cost/hash/identity")
        calls[attempt.call_id] = attempt
        amounts[attempt.call_id] = amount if attempt.liability_status == "known" else None
    issues: list[str] = []
    missing = set() if expected_call_ids is None else set(expected_call_ids) - calls.keys()
    if expected_call_ids is None:
        issues.append("attempt_inventory_unknown")
    elif calls.keys() - set(expected_call_ids):
        raise ValueError("attempt outside exact authoritative inventory")
    issues.extend(f"{call_id}:missing_attempt" for call_id in sorted(missing))
    c_by_task: dict[tuple[str, str], str] = {}
    for call in calls.values():
        if call.arm == "C":
            key = (call.task_id, call.model_slot)
            if key in c_by_task and c_by_task[key] != call.call_id:
                raise ValueError("multiple C call identities for a task/model")
            c_by_task[key] = call.call_id
    for call in calls.values():
        if call.arm in {"D", "R"}:
            expected_c = c_by_task.get((call.task_id, call.model_slot))
            if not call.shared_c_call_id:
                raise ValueError("D/R requires the exact same task/model C call identity")
            if expected_c is None:
                if call.shared_c_call_id in calls:
                    raise ValueError("shared C points to a different task/model/arm")
                if expected_call_ids is not None and call.shared_c_call_id not in expected_call_ids:
                    raise ValueError("shared C outside exact authoritative inventory")
                missing.add(call.shared_c_call_id)
                issues.append(f"{call.shared_c_call_id}:missing_shared_c")
            elif call.shared_c_call_id != expected_c:
                raise ValueError("D/R requires the exact same task/model C call identity")
    coverage = "unknown" if expected_call_ids is None else "incomplete" if missing else "complete"
    inclusive: list[tuple[str, Fraction | None]] = []
    for arm in ARMS:
        ids = {c.call_id for c in calls.values() if c.arm == arm}
        if arm in {"D", "R"}:
            ids.update(c_by_task.values())
        inclusive.append((arm, None if coverage != "complete" or any(amounts[i] is None for i in ids)
                          else sum((amounts[i] for i in ids if amounts[i] is not None), Fraction())))
    unresolved = tuple(sorted(missing | {i for i, amount in amounts.items() if amount is None}))
    issues.extend(f"{call_id}:unresolved_liability" for call_id in sorted(
        i for i, amount in amounts.items() if amount is None))
    known = sum((amount for amount in amounts.values() if amount is not None), Fraction())
    complete = coverage == "complete" and not unresolved
    return CostSummary(len(calls), known, known if complete else None, unresolved, tuple(inclusive),
                       coverage, "complete" if complete else "incomplete", tuple(issues))
